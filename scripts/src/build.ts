type VkSpec = { scheme: 'ultra_honk'; target: string } | { scheme: 'chonk'; kind: 'app' | 'kernel' | 'hiding' };
type Step = { pkg: string; vk: VkSpec; pinned?: string[] };

const ROLLUP = { scheme: 'ultra_honk', target: 'noir-rollup-no-zk' } as const;

// Segments with a Mega app build (P2.28), in their role-3 slot order; seg_quote's app takes slot 0,
// which padding holds in role 3 (a kernel group pads with app_pad instead).
const SEGMENT_KINDS = ['quote', 'block', 'priority', 'trade', 'refresh', 'liquidate', 'forced', 'trigger', 'take', 'quote8'] as const;
// Role 6 holds the first eight apps; app_take (P2.29) is an app slot of the batch role.
const APP_SLOT: Record<string, number> = { ...Object.fromEntries(SEGMENT_KINDS.slice(0, 8).map((k, i) => [`app_${k}`, ROLE.SEGMENT_APP * SHAPE.VK_ROLE_SLOTS + i])), app_take: ROLE.BATCH * SHAPE.VK_ROLE_SLOTS + 4, app_quote8: ROLE.BATCH * SHAPE.VK_ROLE_SLOTS + 5 };

/**
 * Writes each segment's Mega app build, circuits/app_<kind>: the segment's main with its output
 * on the databus (return_data) instead of public inputs, which is how a Chonk app hands its
 * output to the kernel that folds it.
 */
function writeQuote8() {
  const src = readFileSync(join(CIRCUITS, 'seg_quote', 'src', 'main.nr'), 'utf8');
  const out = src
    .replace('global TQ: u32 = 30;', 'global TQ: u32 = 8;')
    .replace('global RL: u32 = 32;', 'global RL: u32 = 8;')
    .replace('global RD: u32 = 5;', 'global RD: u32 = 3;');
  if (out.split('global TQ: u32 = 8;').length !== 2 || out.includes('RL: u32 = 32') || out.includes('RD: u32 = 5;')) throw new Error('seg_quote: TQ/RL/RD not found');
  mkdirSync(join(CIRCUITS, 'seg_quote8', 'src'), { recursive: true });
  writeFileSync(join(CIRCUITS, 'seg_quote8', 'src', 'main.nr'), `// Generated by scripts/src/build.ts from seg_quote/src/main.nr with 8 slots (P2.29). Do not edit.\n${out}`);
  writeFileSync(join(CIRCUITS, 'seg_quote8', 'Nargo.toml'), readFileSync(join(CIRCUITS, 'seg_quote', 'Nargo.toml'), 'utf8').replace('name = "seg_quote"', 'name = "seg_quote8"'));
}

function writeSegmentApps() {
  for (const k of SEGMENT_KINDS) {
    const seg = `seg_${k}`;
    const app = `app_${k}`;
    const src = readFileSync(join(CIRCUITS, seg, 'src', 'main.nr'), 'utf8');
    if (src.split('-> pub NodeOutput {').length !== 2) throw new Error(`${seg}: expected one '-> pub NodeOutput {'`);
    mkdirSync(join(CIRCUITS, app, 'src'), { recursive: true });
    const header = `// Generated by scripts/src/build.ts from ${seg}/src/main.nr (the Mega app build, P2.28). Do not edit.\n`;
    writeFileSync(join(CIRCUITS, app, 'src', 'main.nr'), header + src.replace('-> pub NodeOutput {', '-> return_data NodeOutput {'));
    const toml = readFileSync(join(CIRCUITS, seg, 'Nargo.toml'), 'utf8').replace(`name = "${seg}"`, `name = "${app}"`);
    writeFileSync(join(CIRCUITS, app, 'Nargo.toml'), toml);
  }
}

