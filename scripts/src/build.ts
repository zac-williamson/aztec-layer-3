// Builds the P0 circuit pipeline in dependency order. Before compiling each parent it writes the
// VK hashes of the circuits it verifies into `<parent>/src/pinned.nr`, so every recursive
// verification is pinned to one circuit (SPEC.md §3 G2, §9.3). Writes scripts/out/manifest.json.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Barretenberg } from '@aztec-foundation/bb.js';
import {
  AZTEC_VERSION,
  BB,
  CIRCUITS,
  DS,
  NARGO,
  OUT,
  TARGET,
  VK_DIR,
  fromBytes32,
  hex,
  l3xHash,
  readVkJson,
  run,
  toBytes32,
  writeJson,
} from './lib.ts';

type VkSpec = { scheme: 'ultra_honk'; target: string } | { scheme: 'chonk'; kind: 'app' | 'kernel' | 'hiding' };
type Step = { pkg: string; vk: VkSpec; pinned?: string[] };

// `pinned` lists the hash names (from earlier steps) written into this package before it compiles.
const STEPS: Step[] = [
  { pkg: 'client_auth', vk: { scheme: 'ultra_honk', target: 'noir-recursive' } },
  { pkg: 'agg_app', vk: { scheme: 'chonk', kind: 'app' }, pinned: ['CLIENT_VK_HASH'] },
  { pkg: 'init_kernel', vk: { scheme: 'chonk', kind: 'kernel' }, pinned: ['AGG_APP_VK_HASH'] },
  { pkg: 'tail_kernel', vk: { scheme: 'chonk', kind: 'kernel' }, pinned: ['INIT_KERNEL_VK_HASH'] },
  { pkg: 'hiding_kernel', vk: { scheme: 'chonk', kind: 'hiding' }, pinned: ['TAIL_KERNEL_VK_HASH'] },
  { pkg: 'tube', vk: { scheme: 'ultra_honk', target: 'noir-rollup-no-zk' }, pinned: ['CHONK_VK_HASH'] },
  { pkg: 'padding', vk: { scheme: 'ultra_honk', target: 'noir-rollup-no-zk' } },
  {
    pkg: 'root',
    vk: { scheme: 'ultra_honk', target: 'noir-recursive' },
    pinned: [
      'CLIENT_VK_HASH',
      'AGG_APP_VK_HASH',
      'INIT_KERNEL_VK_HASH',
      'TAIL_KERNEL_VK_HASH',
      'CHONK_VK_HASH',
      'TUBE_VK_HASH',
      'PADDING_VK_HASH',
    ],
  },
  { pkg: 'rogue_app', vk: { scheme: 'chonk', kind: 'app' } },
];

// The hash name each package's VK is published under.
const PUBLISHES: Record<string, string> = {
  client_auth: 'CLIENT_VK_HASH',
  agg_app: 'AGG_APP_VK_HASH',
  init_kernel: 'INIT_KERNEL_VK_HASH',
  tail_kernel: 'TAIL_KERNEL_VK_HASH',
  hiding_kernel: 'CHONK_VK_HASH',
  tube: 'TUBE_VK_HASH',
  padding: 'PADDING_VK_HASH',
  root: 'ROOT_VK_HASH',
  rogue_app: 'ROGUE_APP_VK_HASH',
};

function writePinned(pkg: string, names: string[], hashes: Record<string, string>) {
  const lines = names.map((n) => {
    if (!hashes[n]) throw new Error(`${pkg}: ${n} not yet computed`);
    return `pub global ${n}: Field = ${hashes[n]};`;
  });
  const body = `// Generated by scripts/src/build.ts from bb ${AZTEC_VERSION} VK hashes. Do not edit.\n${lines.join('\n')}\n`;
  writeFileSync(join(CIRCUITS, pkg, 'src', 'pinned.nr'), body);
}

function writeVk(pkg: string, spec: VkSpec) {
  const dir = join(VK_DIR, pkg);
  mkdirSync(dir, { recursive: true });
  const base = ['write_vk', '-b', join(TARGET, `${pkg}.json`), '-o', dir];
  const extra = spec.scheme === 'chonk' ? ['-s', 'chonk', '--circuit_kind', spec.kind] : ['-s', 'ultra_honk', '-t', spec.target];
  run(BB, [...base, ...extra]);
  run(BB, [...base, ...extra, '--output_format', 'json']);
}

async function main() {
  const api = await Barretenberg.new({ threads: 4 });
  const hashes: Record<string, string> = {};
  const timings: Record<string, { compile_ms: number; write_vk_ms: number }> = {};
  for (const step of STEPS) {
    if (step.pinned) writePinned(step.pkg, step.pinned, hashes);
    let t0 = performance.now();
    run(NARGO, ['compile', '--package', step.pkg]);
    const compileMs = performance.now() - t0;
    t0 = performance.now();
    writeVk(step.pkg, step.vk);
    const vkMs = performance.now() - t0;
    const vk = readVkJson(step.pkg);
    // bb reports the hash for UltraHonk VKs only. For Chonk (Mega) VKs compute it the same way bb
    // does for UltraHonk, poseidon2Hash over the VK fields; verified against bb's own hash for
    // client_auth, and confirmed for Mega VKs when the IVC proves (the kernels pin these values).
    const hash = vk.hash || hex(fromBytes32((await api.poseidon2Hash({ inputs: vk.vk.map((f) => toBytes32(BigInt(f))) })).hash));
    if (!vk.hash) writeFileSync(join(VK_DIR, step.pkg, 'vk_hash.hex'), hash + '\n');
    hashes[PUBLISHES[step.pkg]] = hash;
    timings[step.pkg] = { compile_ms: Math.round(compileMs), write_vk_ms: Math.round(vkMs) };
    console.log(`${step.pkg.padEnd(14)} vk ${String(vk.vk.length).padStart(3)} fields  hash ${hash}  (${Math.round(vkMs)} ms)`);
  }

  const h = (name: string) => BigInt(hashes[name]);
  const configHash = await l3xHash(api, [
    DS.CONFIG,
    h('CLIENT_VK_HASH'),
    h('AGG_APP_VK_HASH'),
    h('INIT_KERNEL_VK_HASH'),
    h('TAIL_KERNEL_VK_HASH'),
    h('CHONK_VK_HASH'),
    h('TUBE_VK_HASH'),
    h('PADDING_VK_HASH'),
  ]);
  const genesisStateRoot = await l3xHash(api, [DS.STATE, 0n, 0n, 0n, 0n]);
  await api.destroy();

  writeJson(join(OUT, 'manifest.json'), { aztecVersion: AZTEC_VERSION, hashes, configHash, genesisStateRoot, timings });
  console.log(`config hash        ${'0x' + configHash.toString(16).padStart(64, '0')}`);
  console.log(`wrote ${join(OUT, 'manifest.json')}`);
}

main().catch((err) => {
  console.error(err?.stderr?.toString?.() ?? err);
  process.exit(1);
});
