// Builds the circuits in dependency order and the role-partitioned VK tree (SPEC.md §9.3).
//
// Circuits with a fixed child (the Chonk chain and the tube) pin the child's VK hash as a constant:
// before compiling each, this writes the hashes it verifies into `<pkg>/src/pinned.nr` (G2).
// Merges and the root verify children of several kinds, including merges, so they cannot pin
// constants; they check membership in the VK tree, whose root the configuration commits to.
// Writes scripts/out/manifest.json.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Barretenberg } from '@aztec-foundation/bb.js';
import {
  AZTEC_VERSION,
  BB,
  CIRCUITS,
  NARGO,
  OUT,
  ROLE,
  SHAPE,
  TARGET,
  VK_DIR,
  configHashOf,
  fromBytes32,
  hex,
  readVkJson,
  run,
  toBytes32,
  vkTree,
  writeJson,
} from './lib.ts';
import { hasher, paramsHash as paramsHashOf } from './exchange/model.ts';
import { genesisState, testParams } from './exchange/params.ts';

type VkSpec = { scheme: 'ultra_honk'; target: string } | { scheme: 'chonk'; kind: 'app' | 'kernel' | 'hiding' };
type Step = { pkg: string; vk: VkSpec; pinned?: string[] };

const ROLLUP = { scheme: 'ultra_honk', target: 'noir-rollup-no-zk' } as const;

// `pinned` lists the hash names (from earlier steps) written into this package before it compiles.
const STEPS: Step[] = [
  { pkg: 'client_auth', vk: { scheme: 'ultra_honk', target: 'noir-recursive' } },
  { pkg: 'agg_app', vk: { scheme: 'chonk', kind: 'app' }, pinned: ['CLIENT_VK_HASH'] },
  { pkg: 'init_kernel', vk: { scheme: 'chonk', kind: 'kernel' }, pinned: ['AGG_APP_VK_HASH'] },
  { pkg: 'tail_kernel', vk: { scheme: 'chonk', kind: 'kernel' }, pinned: ['INIT_KERNEL_VK_HASH'] },
  { pkg: 'hiding_kernel', vk: { scheme: 'chonk', kind: 'hiding' }, pinned: ['TAIL_KERNEL_VK_HASH'] },
  { pkg: 'tube', vk: ROLLUP, pinned: ['CHONK_VK_HASH'] },
  { pkg: 'padding', vk: ROLLUP },
  { pkg: 'seg_block', vk: ROLLUP },
  { pkg: 'seg_priority', vk: ROLLUP },
  { pkg: 'seg_trade', vk: ROLLUP },
  { pkg: 'seg_refresh', vk: ROLLUP },
  { pkg: 'seg_liquidate', vk: ROLLUP },
  { pkg: 'seg_forced', vk: ROLLUP },
  { pkg: 'merge', vk: ROLLUP },
  { pkg: 'root', vk: { scheme: 'ultra_honk', target: 'noir-recursive' } },
  { pkg: 'rogue_app', vk: { scheme: 'chonk', kind: 'app' } },
  { pkg: 'rogue_segment', vk: ROLLUP },
  { pkg: 'agg_ultra', vk: ROLLUP, pinned: ['CLIENT_VK_HASH'] },
];

// The hash name each package's VK is published under.
const PUBLISHES: Record<string, string> = {
  client_auth: 'CLIENT_VK_HASH',
  agg_app: 'AGG_APP_VK_HASH',
  init_kernel: 'INIT_KERNEL_VK_HASH',
  tail_kernel: 'TAIL_KERNEL_VK_HASH',
  hiding_kernel: 'CHONK_VK_HASH',
  tube: 'TUBE_VK_HASH',
  padding: 'PADDING_VK_HASH',
  seg_block: 'SEG_BLOCK_VK_HASH',
  seg_priority: 'SEG_PRIORITY_VK_HASH',
  seg_trade: 'SEG_TRADE_VK_HASH',
  seg_refresh: 'SEG_REFRESH_VK_HASH',
  seg_liquidate: 'SEG_LIQUIDATE_VK_HASH',
  seg_forced: 'SEG_FORCED_VK_HASH',
  merge: 'MERGE_VK_HASH',
  root: 'ROOT_VK_HASH',
  rogue_app: 'ROGUE_APP_VK_HASH',
  rogue_segment: 'ROGUE_SEGMENT_VK_HASH',
  agg_ultra: 'AGG_ULTRA_VK_HASH',
};

// VK tree leaf index per package: role subtree, then slot. The root's VK is stored on the Bridge
// instead; the rogue fixtures are deliberately absent, and agg_ultra is a measurement circuit (M1).
const S = SHAPE.VK_ROLE_SLOTS;
const VK_SLOTS: Record<string, number> = {
  client_auth: ROLE.CLIENT * S + 0,
  agg_app: ROLE.CHONK * S + 0,
  init_kernel: ROLE.CHONK * S + 1,
  tail_kernel: ROLE.CHONK * S + 2,
  hiding_kernel: ROLE.CHONK * S + 3,
  tube: ROLE.TUBE * S + 0,
  padding: ROLE.SEGMENT * S + 0,
  seg_block: ROLE.SEGMENT * S + 1,
  seg_priority: ROLE.SEGMENT * S + 2,
  seg_trade: ROLE.SEGMENT * S + 3,
  seg_refresh: ROLE.SEGMENT * S + 4,
  seg_liquidate: ROLE.SEGMENT * S + 5,
  seg_forced: ROLE.SEGMENT * S + 6,
  merge: ROLE.MERGE * S + 0,
};


function writePinned(pkg: string, names: string[], hashes: Record<string, string>) {
  const lines = names.map((n) => {
    if (!hashes[n]) throw new Error(`${pkg}: ${n} not yet computed`);
    return `pub global ${n}: Field = ${hashes[n]};`;
  });
  const body = `// Generated by scripts/src/build.ts from bb ${AZTEC_VERSION} VK hashes. Do not edit.\n${lines.join('\n')}\n`;
  writeFileSync(join(CIRCUITS, pkg, 'src', 'pinned.nr'), body);
}

function writeVk(pkg: string, spec: VkSpec) {
  const dir = join(VK_DIR, pkg);
  mkdirSync(dir, { recursive: true });
  const base = ['write_vk', '-b', join(TARGET, `${pkg}.json`), '-o', dir];
  const extra = spec.scheme === 'chonk' ? ['-s', 'chonk', '--circuit_kind', spec.kind] : ['-s', 'ultra_honk', '-t', spec.target];
  run(BB, [...base, ...extra]);
  run(BB, [...base, ...extra, '--output_format', 'json']);
}

async function main() {
  const api = await Barretenberg.new({ threads: 4 });
  const hashes: Record<string, string> = {};
  const timings: Record<string, { compile_ms: number; write_vk_ms: number }> = {};
  for (const step of STEPS) {
    if (step.pinned) writePinned(step.pkg, step.pinned, hashes);
    let t0 = performance.now();
    run(NARGO, ['compile', '--package', step.pkg]);
    const compileMs = performance.now() - t0;
    t0 = performance.now();
    writeVk(step.pkg, step.vk);
    const vkMs = performance.now() - t0;
    const vk = readVkJson(step.pkg);
    // bb reports the hash for UltraHonk VKs only. For Chonk (Mega) VKs compute it the same way bb
    // does for UltraHonk, poseidon2Hash over the VK fields; verified against bb's own hash for
    // client_auth, and confirmed for Mega VKs when the IVC proves (the kernels pin these values).
    const hash = vk.hash || hex(fromBytes32((await api.poseidon2Hash({ inputs: vk.vk.map((f) => toBytes32(BigInt(f))) })).hash));
    if (!vk.hash) writeFileSync(join(VK_DIR, step.pkg, 'vk_hash.hex'), hash + '\n');
    hashes[PUBLISHES[step.pkg]] = hash;
    timings[step.pkg] = { compile_ms: Math.round(compileMs), write_vk_ms: Math.round(vkMs) };
    console.log(`${step.pkg.padEnd(14)} vk ${String(vk.vk.length).padStart(3)} fields  hash ${hash}  (${Math.round(vkMs)} ms)`);
  }

  const leaves = Array<bigint>(1 << SHAPE.VK_TREE_HEIGHT).fill(0n);
  for (const [pkg, slot] of Object.entries(VK_SLOTS)) leaves[slot] = BigInt(hashes[PUBLISHES[pkg]]);
  const layers = await vkTree(api, leaves);
  const vkTreeRoot = layers[layers.length - 1][0];
  // Default exchange parameters for tests; a deployment chooses its own (scripts/src/exchange/params.ts).
  const h = hasher(api);
  const { params } = await testParams(h);
  const paramsHash = await paramsHashOf(h, params);
  const configHash = await configHashOf(api, vkTreeRoot, paramsHash);
  const genesis = await genesisState(api);
  await api.destroy();

  const vkHashByPkg = Object.fromEntries(Object.entries(PUBLISHES).map(([pkg, name]) => [pkg, hashes[name]]));
  writeJson(join(OUT, 'manifest.json'), {
    aztecVersion: AZTEC_VERSION,
    hashes,
    vkHashByPkg,
    vkTree: { root: vkTreeRoot, slots: VK_SLOTS, leaves },
    params,
    paramsHash,
    configHash,
    genesisTrees: genesis.trees,
    genesisStateRoot: genesis.stateRoot,
    timings,
  });
  console.log(`vk tree root       ${hex(vkTreeRoot)}`);
  console.log(`config hash        ${hex(configHash)}`);
  console.log(`wrote ${join(OUT, 'manifest.json')}`);
}
main().catch((err) => {
  console.error(err?.stderr?.toString?.() ?? err);
  process.exit(1);
});
